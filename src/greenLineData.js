// 3. 幾何平移計算函式：右去左回 (offset > 0 為右軌/去程，offset < 0 為左軌/回程)
function generateParallelOffset(coords, offsetMeters = 5.5) {
  const DEGREE_OFFSET = offsetMeters / 111000;
  const result = [];
  const len = coords.length;

  for (let i = 0; i < len; i++) {
    let dx, dy;
    if (i === 0) {
      dx = coords[1][0] - coords[0][0];
      dy = coords[1][1] - coords[0][1];
    } else if (i === len - 1) {
      dx = coords[len - 1][0] - coords[len - 2][0];
      dy = coords[len - 1][1] - coords[len - 2][1];
    } else {
      dx = coords[i + 1][0] - coords[i - 1][0];
      dy = coords[i + 1][1] - coords[i - 1][1];
    }
    const dist = Math.hypot(dx, dy) || 1;
    // 法向量 (nx, ny)
    const nx = -dy / dist;
    const ny = dx / dist;

    result.push([
      coords[i][0] + nx * DEGREE_OFFSET,
      coords[i][1] + ny * DEGREE_OFFSET
    ]);
  }
  return result;
}

